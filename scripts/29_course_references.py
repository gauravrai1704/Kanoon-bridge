"""The reference list in the course's required format, from docs/paper_acm/references.bib.  [owner: Gaurav — working]

    python scripts/29_course_references.py      -> docs/paper_acm/references_course.tex

Format (CSD358 report guidelines; Harvard style, as Google Scholar exports it):
    Zheng, Y., Zhang, L., Xie, X. and Ma, W.Y., 2009, April. Mining interesting locations and travel
    sequences from GPS trajectories. In Proceedings of the 18th International Conference on World
    Wide Web (pp. 791-800).

Entries are sorted by first author and year and keep their BibTeX keys, so every \\cite still
works; the paper \\input's the file instead of running BibTeX (switch back to
\\bibliography{references} with ACM-Reference-Format for a conference version).
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BIB = ROOT / "docs/paper_acm/references.bib"
OUT = ROOT / "docs/paper_acm/references_course.tex"


def entries(text: str) -> list[dict]:
    out = []
    for m in re.finditer(r"@(\w+)\{([^,]+),(.*?)\n\}", text, re.S):
        e = {"type": m.group(1).lower(), "key": m.group(2).strip()}
        body = m.group(3)
        for f in re.finditer(r"(\w+)\s*=\s*(\{(?:[^{}]|\{(?:[^{}]|\{[^{}]*\})*\})*\}|\d+)", body):
            v = f.group(2)
            e[f.group(1).lower()] = v[1:-1] if v.startswith("{") else v
        out.append(e)
    return out


def _initials(given: str) -> str:
    """'Wei-Ying' -> 'W.Y.', 'Christopher D.' -> 'C.D.', 'M. Mikail' -> 'M.M.'"""
    parts = [p for p in re.split(r"[\s\-~]+", given.replace(".", ". ")) if p]
    return "".join(re.sub(r"[{}\\'\"`^]", "", p)[:1].upper() + "." for p in parts if re.sub(r"[{}\\'\"`^]", "", p))


def authors(field: str) -> str:
    names = [a.strip() for a in re.split(r"\s+and\s+", field) if a.strip()]
    others = names and names[-1].lower() == "others"
    names = [n for n in names if n.lower() != "others"]
    out = []
    for n in names:
        if "," in n:
            last, given = [x.strip() for x in n.split(",", 1)]
        else:
            bits = n.split()
            last, given = bits[-1], " ".join(bits[:-1])
        last = last.strip("{}")
        out.append(f"{last}, {_initials(given)}" if given else last)
    if others:
        return ", ".join(out) + " et al."
    if len(out) == 1:
        return out[0]
    return ", ".join(out[:-1]) + " and " + out[-1]


def clean(t: str) -> str:
    t = re.sub(r"\s+", " ", t or "").strip()
    t = re.sub(r"\{([^{}\\]*)\}", r"\1", t)              # {IL-PCSR} -> IL-PCSR (keeps {\"u})
    return t.rstrip(".")


def pages(p: str) -> str:
    return p.replace("--", "--").strip()


def fmt(e: dict) -> str:
    year = e.get("year", "n.d")
    head = f"{authors(e.get('author', ''))}, {year}. {clean(e.get('title', ''))}."
    t = e["type"]
    if t == "inproceedings":
        tail = f"In \\textit{{{clean(e.get('booktitle', ''))}}}"
        tail += f" (pp. {pages(e['pages'])})." if e.get("pages") else "."
    elif t == "article":
        tail = f"\\textit{{{clean(e.get('journal', ''))}}}"
        if e.get("volume"):
            tail += f", {e['volume']}" + (f"({e['number']})" if e.get("number") else "")
        tail += f", pp.{pages(e['pages'])}." if e.get("pages") else "."
    elif t == "book":
        tail = f"{clean(e.get('publisher', ''))}."
    elif t == "techreport":
        tail = f"Technical report, {clean(e.get('institution', ''))}."
    elif e.get("eprint"):
        tail = f"arXiv preprint arXiv:{e['eprint']}."
    else:
        raw = (e.get("howpublished") or "").strip()
        url = e.get("url", "")
        how = clean(raw)
        if raw.startswith("\\url"):
            tail = f"Available at: {raw}."
        else:
            tail = (f"{how}. " if how else "") + (f"Available at: \\url{{{url}}}." if url else "")
    doi = f" \\url{{https://doi.org/{e['doi']}}}" if e.get("doi") else ""
    return f"{head} {tail}{doi}".strip()


def sort_key(e: dict):
    first = re.split(r"\s+and\s+", e.get("author", ""))[0]
    last = first.split(",")[0] if "," in first else (first.split() or [""])[-1]
    return (re.sub(r"[^a-z]", "", last.lower().replace("de ", "")), e.get("year", ""))


def main() -> None:
    es = sorted(entries(BIB.read_text(encoding="utf-8")), key=sort_key)
    lines = ["% Generated by scripts/29_course_references.py from references.bib - do not edit by hand.",
             f"\\begin{{thebibliography}}{{{len(es)}}}", ""]
    for e in es:
        lines += [f"\\bibitem{{{e['key']}}}", fmt(e), ""]
    lines.append("\\end{thebibliography}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(es)} references)")


if __name__ == "__main__":
    main()
